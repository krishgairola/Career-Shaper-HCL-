import pandas as pd
from google.colab import files

# upload the csv file
uploaded = files.upload()

df = pd.read_csv('Cleaned_mobile_app_usage.csv')
print("Shape of dataset:", df.shape)
df.head()

# checking columns, data types, missing values and duplicates
df.info()
print("\nMissing values:")
print(df.isnull().sum())
print("\nDuplicate rows:", df.duplicated().sum())

"""The file has 1000 rows and 15 columns. There are no missing values and no duplicate rows, so the data is ready for analysis."""

# basic stats for duration and rating
print(df[['Session_Duration_Mins', 'User_Rating']].describe().round(2))

print("\nUnique users:", df['User_ID'].nunique())
print("Total time spent (hours):", round(df['Session_Duration_Mins'].sum() / 60, 2))
print("Average session time (mins):", round(df['Session_Duration_Mins'].mean(), 2))
print("Average rating:", round(df['User_Rating'].mean(), 2))

# feature wise count, average time and average rating
print("Sessions per feature:")
print(df['Feature_Used'].value_counts())

print("\nAverage rating by feature:")
print(df.groupby('Feature_Used')['User_Rating'].mean().round(2).sort_values(ascending=False))

print("\nAverage duration by feature:")
print(df.groupby('Feature_Used')['Session_Duration_Mins'].mean().round(2).sort_values(ascending=False))

# device type analysis
print("Sessions by device:")
print(df['Device_Type'].value_counts())

print("\nAverage duration and rating by device:")
print(df.groupby('Device_Type')[['Session_Duration_Mins', 'User_Rating']].mean().round(2))

# age group and app version analysis
print("Sessions by age group:")
print(df['Age_Group'].value_counts())

print("\nAge group averages:")
print(df.groupby('Age_Group')[['Session_Duration_Mins', 'User_Rating']].mean().round(2))

print("\nApp version averages:")
print(df.groupby('App_Version')[['Session_Duration_Mins', 'User_Rating']].mean().round(2))

# checking high rated vs low rated sessions
high_rating = df[df['User_Rating'] >= 4.0]
low_rating = df[df['User_Rating'] <= 2.5]

print("High rated sessions (4.0 and above):", len(high_rating))
print("Low rated sessions (2.5 and below):", len(low_rating))

# top 5 most active users
print("\nTop 5 users with most sessions:")
print(df['User_ID'].value_counts().head(5))

# correlation between session duration and rating
corr = df['Session_Duration_Mins'].corr(df['User_Rating'])
print("\nCorrelation between duration and rating:", round(corr, 3))

# average rating for each device across app versions
table = pd.pivot_table(df, values='User_Rating', index='Device_Type', columns='App_Version', aggfunc='mean').round(2)
print(table)

